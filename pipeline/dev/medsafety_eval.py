"""Does the automatic medication check (pl/medsafety.py) work, and what does it cost?  Reproduces every number in REPORT section 7.3.

  1. The "expected drug" rule is read off the TRAINING gold only: how often is such a drug recorded, how many gold drugs does it cover?
  2. Dose fill: blank the dose of every training-gold medication fact that has one, fill it from the bullet text, count how often it is right.
  3. The net on saved model outputs: medication scores before and after (same scorer as the matrix), and how many calls it flags.
  4. The review burden: the same flags on the GOLD summaries of the validation set (a perfect summary should rarely be flagged).

Usage: python3 dev/medsafety_eval.py [run ...]      (default: base_v4_s3 finetuned_epoch3_s3)
Writes outputs/medsafety.md and, for every run, outputs/<run>_net/generations.jsonl (the repaired summaries; run `validate` on it to get a matrix).
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from pl import medsafety as MS  # noqa: E402
from pl import reference_metrics as RM  # noqa: E402
from pl.textnorm import normalize  # noqa: E402
from pl.transcript import parse  # noqa: E402

RUNS = sys.argv[1:] or ["base_v4_s3", "finetuned_epoch3_s3"]
val = {c["id"]: c for c in map(json.loads, open(ROOT / "data" / "val_cases.jsonl"))}
trans = {r["call_id"]: r["transcript"] for r in map(json.loads, open(ROOT.parent / "data" / "transcripts" / "train.jsonl"))}
gold = {r["call_id"]: r["target"] for r in map(json.loads, open(ROOT.parent / "data" / "gold" / "train.jsonl"))}


def typed_meds(t, secs=("assessment", "response", "education")):
    return [f for s in secs for b in (t.get(s) or []) for f in (b.get("facts") or []) if f.get("type") == "medication"]


L = ["# Automatic medication check: evaluation", "", "Generated by `dev/medsafety_eval.py`. The rule and the dose extractor were fixed from the training set before being scored on the validation calls.", ""]

# ---- 1. the rule on the training gold
spoken_total = exp_total = exp_in_gold = gold_meds = gold_flagged = 0
for cid, tr in trans.items():
    g = gold[cid]
    if (g.get("not_applicable") or {}).get("is_na"):
        continue
    sp = MS.spoken_drugs(parse(tr))
    names = [str(f.get("name") or "") for f in typed_meds(g)]
    for d, o in sp.items():
        spoken_total += 1
        if MS.expected(o):
            exp_total += 1
            exp_in_gold += any(MS._same(d, n) for n in names)
    detectable = [n for n in names if any(MS._same(d, n) for d in sp)]
    gold_meds += len(detectable)
    gold_flagged += sum(any(MS._same(d, n) and MS.expected(sp[d]) for d in sp) for n in detectable)
L += ["## 1. The rule on the 500 training calls", "",
      f"- Drugs said in a call (formulary matches): {spoken_total}. The rule calls {exp_total} of them *expected* (the caller said it, with a number or in two or more turns).",
      f"- Of the expected drugs, **{exp_in_gold} ({exp_in_gold / exp_total:.0%})** are recorded as a typed medication fact in the training gold.",
      f"- Of the gold's medication facts that a formulary match can find, **{gold_flagged} of {gold_meds} ({gold_flagged / gold_meds:.0%})** are expected drugs.", ""]

# ---- 2. dose fill on the training gold
n = right = filled = 0
for cid, g in gold.items():
    if (g.get("not_applicable") or {}).get("is_na"):
        continue
    for s in MS.SECTIONS:
        for b in g.get(s) or []:
            for f in b.get("facts") or []:
                if f.get("type") == "medication" and f.get("dose"):
                    n += 1
                    got = MS.extract_dose(str(b.get("text") or ""), str(f.get("name") or ""))
                    if got:
                        filled += 1
                        ok = RM._same_dose({"dose": f["dose"], "unit": f.get("unit")}, {"dose": got[0], "unit": got[1]})
                        right += int(ok)
L += ["## 2. Dose fill on the training gold (dose blanked, then filled from the bullet text)", "",
      f"- Medication facts with a dose (with or without a separate strength): {n}. The extractor fills {filled} ({filled / n:.0%}); **{right} of them ({right / filled:.0%}) equal the gold dose and unit**.", ""]

# ---- 3. the net on saved outputs
rows = []
for run in RUNS:
    gens = {r["id"]: r for r in map(json.loads, open(ROOT / "outputs" / run / "generations.jsonl"))}
    before, after = Counter(), Counter()
    flagged = Counter()
    out_rows = []
    for cid, c in val.items():
        r = dict(gens[cid])
        obj = r.get("parsed")
        new, finds = MS.apply(obj, parse(c["transcript"])) if isinstance(obj, dict) else (obj, [])
        if isinstance(obj, dict):
            for tag, o in (("b", obj), ("a", new)):
                sc = RM.score(o, c["gold_target"])
                for k in ("medication_name", "medication_name_dose_unit", "medication_hallucinated"):
                    n_, d_ = sc.get(k, [0, 0])
                    (before if tag == "b" else after)[k + "_n"] += n_
                    (before if tag == "b" else after)[k + "_d"] += d_
        for f in finds:
            flagged[f["rule"]] += 1
        flagged["calls_M3"] += any(f["rule"] == "M3" for f in finds)
        flagged["calls_M1"] += any(f["rule"] == "M1" for f in finds)
        r["parsed"] = new
        r["safety_net"] = [f["rule"] + ":" + f["drug"] for f in finds]
        out_rows.append(r)
    d = ROOT / "outputs" / f"{run}_net"
    d.mkdir(exist_ok=True)
    (d / "generations.jsonl").write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in out_rows) + "\n")
    rows.append((run, before, after, flagged))

L += ["## 3. The net on the saved model outputs (100 validation calls, 75 gold medications)", "",
      "| run | names found before → after | name + dose + unit right before → after | model medication entries unmatched before → after | facts added (M1) | doses filled (M2) | calls flagged: drug said but missing from the summary (M3) |", "|---|---|---|---|---|---|---|"]
for run, b, a, f in rows:
    L.append(f"| {run} | {b['medication_name_n']} → **{a['medication_name_n']}** of 75 | {b['medication_name_dose_unit_n']} → **{a['medication_name_dose_unit_n']}** of 75 | "
             f"{b['medication_hallucinated_n']} → {a['medication_hallucinated_n']} of {b['medication_hallucinated_d']} → {a['medication_hallucinated_d']} | {f['M1']} | {f['M2']} | {f['calls_M3']} of 100 |")

# ---- 4. review burden on the gold itself
g_flag = Counter()
for cid, c in val.items():
    _, finds = MS.apply(c["gold_target"], parse(c["transcript"]))
    g_flag["calls_M3"] += any(f["rule"] == "M3" for f in finds)
    g_flag["calls_M1"] += any(f["rule"] == "M1" for f in finds)
L += ["", "## 4. Review burden: the same net run on the hand-written gold summaries of the validation calls", "",
      f"- Gold summaries flagged M3 (an expected drug missing from the summary): **{g_flag['calls_M3']} of 100**. A perfect summary should rarely be flagged; this is the false-alarm floor.",
      f"- Gold summaries where the net would add a fact (M1): {g_flag['calls_M1']} of 100 (the gold names the drug in the text but gives it no typed fact).", ""]
(ROOT / "outputs" / "medsafety.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
